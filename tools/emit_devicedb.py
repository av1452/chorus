#!/usr/bin/env python3
"""Emit src/chorus/devicedb.py from gen_devicedb.py's JSON output.

Usage:
    python tools/emit_devicedb.py devicedb.json src/chorus/devicedb.py
"""

import json
import sys

d = json.load(open(sys.argv[1]))
out = []
w = out.append

w('"""Hardware tables for Harmony remotes: models, architectures, flash chips.')
w('')
w('A remote reports a numeric *skin* (model index) and *architecture* in its')
w('identity response. The architecture determines where the config, firmware')
w('and serial number live in the address space; the flash manufacturer/device')
w('ID pair determines total size and the sector map used for erases.')
w('')
w('Transcribed from libconcord\'s remote_info.h (GPLv3) by Kevin Timmerman and')
w('Phil Dibowitz. Generated -- see tools/gen_devicedb.py. See NOTICE.md.')
w('"""')
w('')
w('from __future__ import annotations')
w('')
w('from dataclasses import dataclass')
w('')
w('#: Serial number lives in the microcontroller\'s EEPROM.')
w('SERIAL_IN_EEPROM = "eeprom"')
w('#: Serial number lives in external flash.')
w('SERIAL_IN_FLASH = "flash"')
w('')
w('#: Sentinel ``config_base`` meaning "look the region up in the on-remote')
w('#: region table" rather than using a fixed address. Z-Wave and usbnet')
w('#: remotes (890, 900, 1100) do this.')
w('REGION_USER_CONFIG = -1')
w('')
w('')
w('@dataclass(frozen=True)')
w('class Model:')
w('    """A remote model, indexed by the skin ID the remote reports."""')
w('')
w('    manufacturer: str')
w('    name: str')
w('    skin: str | None = None')
w('')
w('    @property')
w('    def known(self) -> bool:')
w('        return self.manufacturer != "Unknown"')
w('')
w('')
w('@dataclass(frozen=True)')
w('class Flash:')
w('    """An external flash chip, identified by (manufacturer, device) ID."""')
w('')
w('    manufacturer_id: int')
w('    device_id: int')
w('    size_kb: int')
w('    bits: int')
w('    sectors: tuple[int, ...]')
w('    name: str')
w('')
w('    @property')
w('    def size_bytes(self) -> int:')
w('        return self.size_kb << 10')
w('')
w('')
w('@dataclass(frozen=True)')
w('class Architecture:')
w('    """Address-space layout for a family of remotes."""')
w('')
w('    index: int')
w('    serial_location: str | int')
w('    serial_address: int')
w('    flash_base: int')
w('    firmware_base: int')
w('    config_base: int')
w('    firmware_update_base: int')
w('    firmware_4847_offset: int')
w('    cookie: int')
w('    cookie_size: int')
w('    end_vector: int')
w('    micro: str')
w('    flash_size: int')
w('    ram_size: int')
w('    eeprom_size: int')
w('    usb: str')
w('')
w('    @property')
w('    def supported(self) -> bool:')
w('        """False for placeholder entries we have no layout data for."""')
w('        return self.cookie != 0')
w('')
w('')
w('# ---------------------------------------------------------------------------')
w('# Flash sector maps. Each entry is the END address of a sector, so sector N')
w('# spans [sectors[N-1], sectors[N]).')
w('# ---------------------------------------------------------------------------')
w('')
for name, vals in sorted(d["sectors"].items()):
    w(f'{name.upper()} = (')
    line = '    '
    for v in vals:
        tok = f'0x{v:06X}, '
        if len(line) + len(tok) > 76:
            w(line.rstrip()); line = '    '
        line += tok
    if line.strip(): w(line.rstrip())
    w(')')
    w('')

w('')
w('#: Every known flash chip, keyed by ``(manufacturer_id, device_id)``.')
w('FLASH_CHIPS: dict[tuple[int, int], Flash] = {')
for mfg, fid, size, bits, sec, name in d["flashes"]:
    w(f'    (0x{mfg:02X}, 0x{fid:02X}): Flash(')
    w(f'        0x{mfg:02X}, 0x{fid:02X}, {size}, {bits}, {sec.upper()}, "{name}"')
    w('    ),')
w('}')
w('')
w('#: Fallback used when a remote reports a flash ID we have no entry for.')
w('UNKNOWN_FLASH = Flash(0, 0, 1024, 8, SECTORS1, "unknown flash")')
w('')
w('')
w('MODELS: tuple[Model, ...] = (')
for i, (mfg, name, skin) in enumerate(d["models"]):
    s = 'None' if skin is None else f'"{skin}"'
    w(f'    Model("{mfg}", "{name}", {s}),  # {i}')
w(')')
w('')
w('')
w('ARCHITECTURES: tuple[Architecture, ...] = (')
for idx, a in d["archs"]:
    sl = a["serial_location"]
    sl = f'SERIAL_IN_{sl.upper()}' if isinstance(sl, str) else str(sl)
    cb = a["config_base"]
    cb = 'REGION_USER_CONFIG' if cb == "REGION_USER_CONFIG" else f'0x{cb:06X}'
    w('    Architecture(')
    w(f'        index={idx},')
    w(f'        serial_location={sl},')
    w(f'        serial_address=0x{a["serial_address"]:06X},')
    w(f'        flash_base=0x{a["flash_base"]:06X},')
    w(f'        firmware_base=0x{a["firmware_base"]:06X},')
    w(f'        config_base={cb},')
    w(f'        firmware_update_base=0x{a["firmware_update_base"]:06X},')
    w(f'        firmware_4847_offset={a["firmware_4847_offset"]},')
    w(f'        cookie=0x{a["cookie"]:08X},')
    w(f'        cookie_size={a["cookie_size"]},')
    w(f'        end_vector={a["end_vector"]},')
    w(f'        micro="{a["micro"]}",')
    w(f'        flash_size={a["flash_size"]},')
    w(f'        ram_size={a["ram_size"]},')
    w(f'        eeprom_size={a["eeprom_size"]},')
    w(f'        usb="{a["usb"]}",')
    w('    ),')
w(')')
w('')
w('')
w('def model_for_skin(skin: int) -> Model:')
w('    """Look up a model by reported skin ID, clamping out-of-range values."""')
w('    if 0 <= skin < len(MODELS):')
w('        return MODELS[skin]')
w('    return Model("Unknown", f"skin {skin}", None)')
w('')
w('')
w('def architecture(index: int) -> Architecture | None:')
w('    """Look up an architecture by reported index, or None if unknown."""')
w('    if 0 <= index < len(ARCHITECTURES):')
w('        return ARCHITECTURES[index]')
w('    return None')
w('')
w('')
w('def flash_chip(manufacturer_id: int, device_id: int) -> Flash:')
w('    """Look up a flash chip, falling back to a conservative default.')
w('')
w('    Some firmware reports the manufacturer and device IDs swapped, so we')
w('    try both orders before giving up.')
w('    """')
w('    chip = FLASH_CHIPS.get((manufacturer_id, device_id))')
w('    if chip is None:')
w('        chip = FLASH_CHIPS.get((device_id, manufacturer_id))')
w('    return chip or UNKNOWN_FLASH')
w('')
w('')
w('def search_models(query: str) -> list[tuple[int, Model]]:')
w('    """Case-insensitive substring search over known model names."""')
w('    q = query.lower()')
w('    return [')
w('        (i, m)')
w('        for i, m in enumerate(MODELS)')
w('        if m.known and q in m.name.lower()')
w('    ]')
open(sys.argv[2],"w").write("\n".join(out) + "\n")
